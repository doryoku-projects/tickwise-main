#!/usr/bin/env node
/*
 * Snapshot address -> symbol for every CoinGecko-listed token on a chain.
 *
 * WHY: the Envio indexer reads ERC-20 metadata once, at pool creation, and never
 * revisits it. On Robinhood Chain the public RPC rate-limits hardest early in a
 * sync — measured 18.4% metadata failures in the oldest blocks falling to 2.5%
 * in the newest — and every failure is frozen in as the literal "UNKNOWN".
 * Re-reading them on-chain means a resync of 53M blocks.
 *
 * Measured coverage: of the 248 tokens in 4663 pools holding over $100k, 95 are
 * UNKNOWN and 77 of those (81%) are listed on CoinGecko. So this recovers most
 * of what a user actually sees, for the cost of one HTTP call at build time.
 *
 * SYMBOL ONLY, deliberately. Decimals are NOT recovered here: the indexer has
 * already computed every amount, price and TVL using the decimals it stored, so
 * retroactively changing one would make new reads disagree with the aggregates
 * already written. A wrong symbol is cosmetic; a wrong decimal is a wrong number.
 * Decimals must be fixed in the indexer and re-synced, not patched at read time.
 *
 *   node scripts/refresh-token-symbols.mjs [platform]   # default: robinhood
 *
 * COINGECKO_API_KEY switches to the pro host. Never invoked at runtime.
 */

import { writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

// Keyed by CoinGecko asset-platform id, exactly like refresh-token-allowlist.mjs.
// The key must equal ChainConfig.coingeckoPlatformId for the chain.
const TARGETS = {
  robinhood: { file: 'token-symbols.robinhood.ts', constName: 'ROBINHOOD_TOKEN_SYMBOLS', chainId: 4663, label: 'Robinhood Chain' },
};

const PLATFORM = process.argv[2] || 'robinhood';
const target = TARGETS[PLATFORM];
if (!target) {
  throw new Error(`Unknown platform '${PLATFORM}'. Known: ${Object.keys(TARGETS).join(', ')}`);
}
const { file: OUT_FILE, constName: CONST_NAME, chainId: CHAIN_ID, label: LABEL } = target;

const KEY = process.env.COINGECKO_API_KEY;
const BASE = KEY ? 'https://pro-api.coingecko.com/api/v3' : 'https://api.coingecko.com/api/v3';
const HEADERS = KEY
  ? { accept: 'application/json', 'x-cg-pro-api-key': KEY }
  : { accept: 'application/json' };

console.log(`Fetching coins/list from ${KEY ? 'pro' : 'free'} CoinGecko…`);
const res = await fetch(`${BASE}/coins/list?include_platform=true`, { headers: HEADERS });
if (!res.ok) throw new Error(`coins/list HTTP ${res.status}`);
const coins = await res.json();
if (!Array.isArray(coins) || coins.length === 0) throw new Error('coins/list empty');

const entries = new Map();
for (const c of coins) {
  const addr = c?.platforms?.[PLATFORM];
  if (typeof addr !== 'string' || !addr.startsWith('0x') || addr.length !== 42) continue;
  const symbol = String(c.symbol ?? '').trim().toUpperCase();
  // A blank or absurd symbol is worse than showing UNKNOWN, which at least
  // reads as "not known" rather than as a real ticker.
  if (!symbol || symbol.length > 16) continue;
  entries.set(addr.toLowerCase(), symbol);
}
if (entries.size === 0) throw new Error(`no ${PLATFORM} contract addresses resolved`);

const sorted = [...entries.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
console.log(`Collected ${sorted.length} ${PLATFORM} token symbols from ${coins.length} coins.`);

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '..', 'src', 'pricing', 'data', OUT_FILE);

const body = `// AUTO-GENERATED by scripts/refresh-token-symbols.mjs — DO NOT EDIT BY HAND.
// Snapshot of CoinGecko-listed ${LABEL} token symbols, for display recovery when
// the indexer's on-chain metadata read failed. SYMBOL ONLY — never decimals.
// Regenerate: node scripts/refresh-token-symbols.mjs ${PLATFORM}
export const SYMBOL_META = {
  source: 'coingecko:coins/list?include_platform=true',
  platform: '${PLATFORM}',
  chainId: ${CHAIN_ID},
  count: ${sorted.length},
  generatedAt: '${new Date().toISOString().slice(0, 10)}',
} as const;

/** Lowercased contract address -> symbol, for ${LABEL}. */
export const ${CONST_NAME}: ReadonlyMap<string, string> = new Map([
${sorted.map(([a, s]) => `  ['${a}', '${s}'],`).join('\n')}
]);
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, body);
console.log(`Wrote ${OUT}`);
