#!/usr/bin/env node
/*
 * Snapshot the tokenized equities on Robinhood Chain (4663) as a committed
 * address -> ticker map.
 *
 * WHY COMMITTED, not fetched at runtime: same reasoning as the token allowlist —
 * the result must be deterministic and must work server-side with no network,
 * and free CoinGecko IP-blocks cloud egress, so a runtime fetch fails silently.
 *
 * WHY BY ADDRESS, never by symbol: on 4663 a symbol is attacker-controlled.
 * ponder/DEPLOY.md documents a fake USDG with 104k holders and reputation "ok",
 * and the real USDG is out-held by 18-decimal impostors. 193 canonical equity
 * tickers (AAPL, TSLA, NVDA…) are the obvious next target. The CoinGecko
 * category membership paired with the on-chain contract address is the only
 * authenticating link; the ticker alone authenticates nothing.
 *
 * WHY THIS ALSO FIXES DISPLAY: the indexer's ERC-20 metadata read rate-limits on
 * 4663 and falls back to the literal "UNKNOWN"
 * (uniswap-v4-indexer-envio/src/utils/tokenMetadata.ts). 94 of the 97 indexed
 * stock tokens that HAVE pools are stored as UNKNOWN. This map recovers the
 * ticker at read time without reindexing 53M blocks.
 *
 *   node scripts/refresh-tokenized-equities.mjs
 *
 * COINGECKO_API_KEY switches to the pro host. Never invoked at runtime.
 */

import { writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

// CoinGecko's own category for the chain's equity tokens. Verified 2026-09-02:
// 193 members, every one carrying a `platforms.robinhood` contract address.
const CATEGORY = 'robinhood-chain-stocks-ecosystem';
// Must equal ChainConfig.coingeckoPlatformId for 4663, or the join finds nothing.
const PLATFORM = 'robinhood';
const CHAIN_ID = 4663;
const OUT_FILE = 'tokenized-equities.robinhood.ts';
const CONST_NAME = 'ROBINHOOD_EQUITIES';

const KEY = process.env.COINGECKO_API_KEY;
const BASE = KEY ? 'https://pro-api.coingecko.com/api/v3' : 'https://api.coingecko.com/api/v3';
const HEADERS = KEY
  ? { accept: 'application/json', 'x-cg-pro-api-key': KEY }
  : { accept: 'application/json' };

async function getJson(path) {
  const res = await fetch(`${BASE}${path}`, { headers: HEADERS });
  if (!res.ok) throw new Error(`${path} HTTP ${res.status}`);
  return res.json();
}

console.log(`Fetching ${CATEGORY} from ${KEY ? 'pro' : 'free'} CoinGecko…`);

// Two requests. The category call gives membership + ticker; it does NOT include
// contract addresses, so the platform map is joined in from coins/list — the
// same endpoint refresh-token-allowlist.mjs already uses.
const markets = await getJson(
  `/coins/markets?vs_currency=usd&category=${CATEGORY}&per_page=250&page=1`,
);
if (!Array.isArray(markets) || markets.length === 0) throw new Error('category empty');
if (markets.length === 250) {
  // per_page caps at 250; a full page means members were silently dropped.
  throw new Error('category returned a full page — add pagination before trusting this snapshot');
}

const coins = await getJson('/coins/list?include_platform=true');
if (!Array.isArray(coins) || coins.length === 0) throw new Error('coins/list empty');
const platformById = new Map(coins.map((c) => [c.id, c?.platforms?.[PLATFORM]]));

const entries = new Map();
let missingAddress = 0;
for (const m of markets) {
  const addr = platformById.get(m.id);
  if (typeof addr !== 'string' || !addr.startsWith('0x') || addr.length !== 42) {
    missingAddress += 1;
    continue;
  }
  const ticker = String(m.symbol ?? '').toUpperCase();
  if (!ticker) continue;
  entries.set(addr.toLowerCase(), ticker);
}
if (entries.size === 0) throw new Error('no equity contract addresses resolved');

const sorted = [...entries.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
console.log(
  `Collected ${sorted.length} tokenized equities on ${PLATFORM}` +
    (missingAddress ? ` (${missingAddress} category members had no ${PLATFORM} address)` : ''),
);

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '..', 'src', 'pricing', 'data', OUT_FILE);

const body = `// AUTO-GENERATED by scripts/refresh-tokenized-equities.mjs — DO NOT EDIT BY HAND.
// Snapshot of CoinGecko-listed tokenized equities on Robinhood Chain (${CHAIN_ID}).
// Regenerate: node scripts/refresh-tokenized-equities.mjs
export const EQUITY_META = {
  source: 'coingecko:coins/markets?category=${CATEGORY}',
  platform: '${PLATFORM}',
  chainId: ${CHAIN_ID},
  count: ${sorted.length},
  generatedAt: '${new Date().toISOString().slice(0, 10)}',
} as const;

/** Lowercased contract address -> equity ticker, for Robinhood Chain. */
export const ${CONST_NAME}: ReadonlyMap<string, string> = new Map([
${sorted.map(([a, s]) => `  ['${a}', '${s}'],`).join('\n')}
]);
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, body);
console.log(`Wrote ${OUT}`);
