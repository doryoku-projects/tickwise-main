#!/usr/bin/env node
/**
 * Regenerates a committed CoinGecko-listed token allowlist used by the pricing
 * trust gate (src/pricing/data/token-allowlist.<chain>.ts).
 *
 * WHY committed: the gate must be deterministic and work server-side with no
 * runtime network. Free CoinGecko (api.coingecko.com) IP-rate-limits/blocks cloud
 * IPs, so a runtime fetch fails silently. We snapshot the list at commit time
 * instead — a token is "real-market" iff CoinGecko lists a contract for it, so a token CoinGecko does not list
 * is valued at $0 (e.g. PORT3/XRPC).
 *
 * Run manually or in CI (e.g. weekly), one CoinGecko asset-platform id per chain:
 *   node scripts/refresh-token-allowlist.mjs            # ethereum (default)
 *   node scripts/refresh-token-allowlist.mjs avalanche
 * The platform id must match the chain's `coingeckoPlatformId` in chains.config.ts
 * (that is the key BY_PLATFORM looks the snapshot up under at runtime).
 * Uses COINGECKO_API_KEY (pro host) if set in the environment, else the free tier.
 * Never invoked at runtime.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

// One target per chain, keyed by the CoinGecko asset-platform id (= the chain's
// `coingeckoPlatformId`). `file` is the committed snapshot; `constName` is the
// exported Set; `label` is the human chain name woven into the file's comments.
const TARGETS = {
  ethereum: { file: 'token-allowlist.eth.ts', constName: 'ETH_ALLOWLIST', label: 'Ethereum' },
  avalanche: { file: 'token-allowlist.avax.ts', constName: 'AVAX_ALLOWLIST', label: 'Avalanche C-Chain' },
  // Keys are CoinGecko ASSET PLATFORM ids, which is also what
  // `ChainConfig.coingeckoPlatformId` holds and what `BY_PLATFORM` is keyed by —
  // all three must agree or `isAllowlisted` silently fails open.
  'arbitrum-one': { file: 'token-allowlist.arbitrum.ts', constName: 'ARBITRUM_ALLOWLIST', label: 'Arbitrum One' },
  robinhood: { file: 'token-allowlist.robinhood.ts', constName: 'ROBINHOOD_ALLOWLIST', label: 'Robinhood Chain' },
};

const PLATFORM = process.argv[2] || 'ethereum';
const target = TARGETS[PLATFORM];
if (!target) {
  throw new Error(`Unknown platform '${PLATFORM}'. Known: ${Object.keys(TARGETS).join(', ')}`);
}
const { file: OUT_FILE, constName: CONST_NAME, label: LABEL } = target;
const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '..', 'src', 'pricing', 'data', OUT_FILE);

const key = process.env.COINGECKO_API_KEY;
const base = key ? 'https://pro-api.coingecko.com/api/v3' : 'https://api.coingecko.com/api/v3';
const headers = { accept: 'application/json', ...(key ? { 'x-cg-pro-api-key': key } : {}) };

console.log(`Fetching coins/list from ${key ? 'pro' : 'free'} CoinGecko…`);
const res = await fetch(`${base}/coins/list?include_platform=true`, { headers });
if (!res.ok) throw new Error(`coins/list HTTP ${res.status}`);
const coins = await res.json();
if (!Array.isArray(coins) || coins.length === 0) throw new Error('coins/list empty');

const addresses = new Set();
for (const c of coins) {
  const addr = c?.platforms?.[PLATFORM];
  if (typeof addr === 'string' && addr.startsWith('0x') && addr.length === 42) {
    addresses.add(addr.toLowerCase());
  }
}
const sorted = [...addresses].sort();
console.log(`Collected ${sorted.length} ${PLATFORM} contract addresses from ${coins.length} coins.`);

const body = `// AUTO-GENERATED by scripts/refresh-token-allowlist.mjs — DO NOT EDIT BY HAND.
// Snapshot of CoinGecko-listed ${LABEL} token contract addresses (real-market gate).
// Regenerate: node scripts/refresh-token-allowlist.mjs ${PLATFORM}
export const ALLOWLIST_META = {
  source: 'coingecko:coins/list?include_platform=true',
  platform: '${PLATFORM}',
  count: ${sorted.length},
  generatedAt: '${new Date().toISOString().slice(0, 10)}',
} as const;

/** Lowercased CoinGecko-listed ${LABEL} contract addresses. */
export const ${CONST_NAME}: ReadonlySet<string> = new Set([
${sorted.map((a) => `  '${a}',`).join('\n')}
]);
`;
await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, body);
console.log(`Wrote ${OUT}`);
